// Writes src/tui/cell_width_table.h: the cells each code point takes in a terminal, as glibc's wcwidth()
// counts them in C.UTF-8 (the Unicode tables Linux terminals follow), for Windows, which has no wcwidth.
//   g++ -O2 tools/gen_cell_width_table.cpp -o build/gen_cell_width_table
//   build/gen_cell_width_table > src/tui/cell_width_table.h
#include <gnu/libc-version.h>

#include <clocale>
#include <cstdio>
#include <cwchar>

int main() {
    if (!setlocale(LC_CTYPE, "C.UTF-8")) return 1;
    std::printf("// Generated by tools/gen_cell_width_table.cpp from glibc %s's wcwidth (C.UTF-8): do not edit.\n"
                "// From U+0300 on, the code points whose width isn't 1, in order: {first, last, width} (2 wide,\n"
                "// 0 zero-width, -1 not printable).\n#pragma once\n\nnamespace tui {\n\n"
                "struct CellWidthRange {\n    char32_t first, last;\n    signed char width;\n};\n\n"
                "constexpr CellWidthRange CELL_WIDTH_RANGES[] = {\n",
                gnu_get_libc_version());
    int n = 0, cur = 1;
    unsigned first = 0;
    for (unsigned cp = 0x300; cp <= 0x110000; cp++) {
        int w = cp == 0x110000 ? 1 : (cp >= 0xD800 && cp <= 0xDFFF) ? -1 : wcwidth((wchar_t)cp);
        if (w != cur) {
            if (cur != 1) std::printf("    {0x%X, 0x%X, %d},\n", first, cp - 1, cur), n++;
            cur = w, first = cp;
        }
    }
    std::printf("};\n\n}  // namespace tui\n");
    std::fprintf(stderr, "%d ranges\n", n);
}
